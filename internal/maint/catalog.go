package maint

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strconv"

	"github.com/Cyenoch/mygoicons/generate"
)

// Catalog emits a directory only for the native development example.
func Catalog(root string, changes map[string][]byte) ([]byte, error) {
	read := func(name string) ([]byte, error) {
		if data, ok := changes[name]; ok {
			return data, nil
		}
		return os.ReadFile(filepath.Join(root, name))
	}
	raw, err := read("sources/lock.json")
	if err != nil {
		return nil, err
	}
	var lock Lock
	if err = json.Unmarshal(raw, &lock); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by mygoicons catalog; DO NOT EDIT.\npackage main\nimport (\"github.com/egoist/mygo/ui\";\"github.com/Cyenoch/mygoicons/lucide\";\"github.com/Cyenoch/mygoicons/twemoji\")\ntype entry struct {Name, ID string; SVG func() *ui.SVG}\ntype collection struct {Prefix, Version, License string; Icons []entry}\nvar collections = []collection{\n")
	for _, c := range lock.Collections {
		data, err := read(filepath.Join(c.Prefix, "icons_gen.go"))
		if err != nil {
			return nil, err
		}
		exports, err := generate.ReadExports(data)
		if err != nil {
			return nil, err
		}
		var license struct{ Title, SPDX string }
		if err = json.Unmarshal(c.License.Metadata, &license); err != nil {
			return nil, err
		}
		label := license.SPDX
		if c.Prefix == "lucide" {
			label += "; Feather-derived artwork: MIT"
		} else {
			label += "; Twitter and Twemoji contributors"
		}
		fmt.Fprintf(&out, "{Prefix:%q,Version:%q,License:%q,Icons:[]entry{\n", c.Prefix, c.Version, label)
		for _, e := range exports {
			fmt.Fprintf(&out, "{%s,%s,%s.%s},\n", strconv.Quote(e.Name), strconv.Quote(e.ID), c.Prefix, e.Name)
		}
		out.WriteString("}},\n")
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}
