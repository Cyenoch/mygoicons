package maint

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"strings"

	"github.com/Cyenoch/mygoicons/generate"
)

// Catalog emits the public catalog package's listing of every accessor.
func Catalog(root string, changes map[string][]byte) ([]byte, error) {
	read := func(name string) ([]byte, error) {
		if data, ok := changes[name]; ok {
			return data, nil
		}
		return os.ReadFile(filepath.Join(root, name))
	}
	readJSON := func(name string, into any) error {
		data, err := read(name)
		if err != nil {
			return err
		}
		if err := json.Unmarshal(data, into); err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		return nil
	}
	var lock Lock
	if err := readJSON("sources/lock.json", &lock); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by mygoicons catalog; DO NOT EDIT.\n\npackage catalog\n\nimport (\n")
	for _, c := range lock.Collections {
		fmt.Fprintf(&out, "%q\n", "github.com/Cyenoch/mygoicons/"+c.Prefix)
	}
	out.WriteString(")\n\n// All returns every bundled collection.\nfunc All() []Collection { return []Collection{")
	for _, c := range lock.Collections {
		fmt.Fprintf(&out, "%s(),", exportedPrefix(c.Prefix))
	}
	out.WriteString("} }\n\n")
	for _, c := range lock.Collections {
		dir := filepath.Join("sources", c.Prefix)
		var exports []generate.Export
		if err := readJSON(filepath.Join(dir, "exports.json"), &exports); err != nil {
			return nil, err
		}
		var info struct {
			Name    string
			Palette bool
		}
		if err := readJSON(filepath.Join(dir, "info.json"), &info); err != nil {
			return nil, err
		}
		var source struct{ Icons map[string]json.RawMessage }
		if err := readJSON(filepath.Join(dir, "icons.json"), &source); err != nil {
			return nil, err
		}
		var license struct{ SPDX string }
		if err := json.Unmarshal(c.License.Metadata, &license); err != nil {
			return nil, err
		}
		label := license.SPDX
		if c.Prefix == "lucide" {
			label += "; Feather-derived artwork: MIT"
		} else {
			label += "; Twitter and Twemoji contributors"
		}
		// The drawing's own icon stands for it; its aliases point there.
		original := make(map[string]string, len(exports))
		for _, e := range exports {
			if _, drawn := source.Icons[e.ID]; drawn && original[e.SHA256] == "" {
				original[e.SHA256] = e.Name
			}
		}
		for _, e := range exports {
			if original[e.SHA256] == "" {
				original[e.SHA256] = e.Name
			}
		}
		name := exportedPrefix(c.Prefix)
		fmt.Fprintf(&out, "// %s returns the %s collection, %s %s.\n", name, info.Name, c.Package, c.Version)
		fmt.Fprintf(&out, "func %s() Collection {\nreturn Collection{Prefix:%q,Title:%q,Version:%q,License:%q,Colored:%t,Icons:%sIcons}\n}\n\n",
			name, c.Prefix, info.Name, c.Version, label, info.Palette, c.Prefix)
		fmt.Fprintf(&out, "var %sIcons = []Icon{\n", c.Prefix)
		for _, e := range exports {
			alias := original[e.SHA256]
			if alias == e.Name {
				alias = ""
			}
			fmt.Fprintf(&out, "{%q,%q,%q,%s.%s},\n", e.Name, e.ID, alias, c.Prefix, e.Name)
		}
		out.WriteString("}\n\n")
	}
	return format.Source(out.Bytes())
}

// exportedPrefix is a collection prefix as a Go identifier: lucide, Lucide.
func exportedPrefix(prefix string) string {
	return strings.ToUpper(prefix[:1]) + strings.ReplaceAll(prefix[1:], "-", "")
}
