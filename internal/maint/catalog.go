package maint

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"

	"github.com/Cyenoch/mygoicons/generate"
)

// Catalog emits a directory only for the native development example.
func Catalog(root string, changes map[string][]byte) ([]byte, error) {
	read := func(name string) ([]byte, error) {
		if data, ok := changes[name]; ok {
			return data, nil
		}
		return os.ReadFile(filepath.Join(root, name))
	}
	raw, err := read("sources/lock.json")
	if err != nil {
		return nil, err
	}
	var lock Lock
	if err = json.Unmarshal(raw, &lock); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	out.WriteString(`// Code generated by mygoicons catalog; DO NOT EDIT.
package main
import (
 "github.com/egoist/mygo/ui"
 "github.com/Cyenoch/mygoicons/lucide"
 "github.com/Cyenoch/mygoicons/twemoji"
)
type entry struct {Name, ID string; SVG func() *ui.SVG}
type collection struct {Prefix, Version, License string; Icons []entry}
var collections = []collection{
`)
	for _, c := range lock.Collections {
		data, err := read(filepath.Join("sources", c.Prefix, "exports.json"))
		if err != nil {
			return nil, err
		}
		var exports []generate.Export
		if err := json.Unmarshal(data, &exports); err != nil {
			return nil, err
		}
		var license struct{ SPDX string }
		if err = json.Unmarshal(c.License.Metadata, &license); err != nil {
			return nil, err
		}
		label := license.SPDX
		if c.Prefix == "lucide" {
			label += "; Feather-derived artwork: MIT"
		} else {
			label += "; Twitter and Twemoji contributors"
		}
		fmt.Fprintf(&out, "{Prefix:%q,Version:%q,License:%q,Icons:[]entry{\n", c.Prefix, c.Version, label)
		for _, e := range exports {
			fmt.Fprintf(&out, "{%q,%q,%s.%s},\n", e.Name, e.ID, c.Prefix, e.Name)
		}
		out.WriteString("}},\n")
	}
	out.WriteString("}\n")
	return format.Source(out.Bytes())
}
