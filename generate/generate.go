// Package generate turns Iconify JSON into standalone MyGo icon packages.
// Generation validates input and renderer compatibility before producing source.
package generate

import (
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"slices"
	"strconv"
)

// Version identifies the generated source format and validation policy.
const Version = "0.1.0"

// Options selects the generated Go package and, optionally, a subset of icons.
// An empty Icons slice selects the entire collection, including aliases.
type Options struct {
	Package string
	Icons   []string
	// Previous protects existing accessors. Removed names require a unique
	// identical replacement; naming changes produce forwarding functions.
	Previous []Export
}

// Result is a complete generated Go file with the identity of its input.
type Result struct {
	Source  []byte
	Prefix  string
	Count   int
	SHA256  string
	Exports []Export
}

// Build validates a collection and emits deterministic source. It never
// accesses the network or filesystem. Errors identify the original Iconify ID.
func Build(data []byte, options Options) (Result, error) {
	if err := checkPackage(options.Package); err != nil {
		return Result{}, err
	}
	if len(options.Icons) > MaxIcons {
		return Result{}, fmt.Errorf("selection exceeds %d icons", MaxIcons)
	}
	c, err := readCollection(data)
	if err != nil {
		return Result{}, err
	}
	names := c.names()
	if len(options.Icons) != 0 {
		names = slices.Clone(options.Icons)
		slices.Sort(names)
		names = slices.Compact(names)
	}
	resolver := resolver{collection: c, cache: make(map[string]properties), active: make(map[string]bool)}
	sum := fmt.Sprintf("%x", sha256.Sum256(data))
	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by mygoicons %s; DO NOT EDIT.\n", Version)
	fmt.Fprintf(&source, "// Iconify collection: %s; input SHA-256: %s.\n", c.Prefix, sum)
	fmt.Fprintf(&source, "// Package %s provides %s icons for MyGo. Each function parses once on first use.\n", options.Package, c.Prefix)
	fmt.Fprintf(&source, "package %s\n\nimport (\n\"sync\"\n\"github.com/egoist/mygo/ui\"\n)\n\n", options.Package)
	source.WriteString(`type iconCache struct {
	once sync.Once
	svg *ui.SVG
}

func (cache *iconCache) load(source string) *ui.SVG {
	cache.once.Do(func() { cache.svg = ui.MustParseSVG([]byte(source)) })
	return cache.svg
}

`)
	exports := make([]Export, 0, len(names))
	exported := make(map[string]string, len(names))
	for index, name := range names {
		if !iconName.MatchString(name) || len(name) > 256 {
			return Result{}, fmt.Errorf("%s: invalid selected icon name %q", c.Prefix, name)
		}
		symbol := exportedName(name)
		if previous, exists := exported[symbol]; exists {
			return Result{}, fmt.Errorf("%s:%s and %s:%s both generate Go name %s", c.Prefix, previous, c.Prefix, name, symbol)
		}
		exported[symbol] = name
		p, err := resolver.resolve(name, 0)
		if err != nil {
			return Result{}, fmt.Errorf("%s:%s: %w", c.Prefix, name, err)
		}
		icon, err := c.complete(p)
		if err != nil {
			return Result{}, fmt.Errorf("%s:%s: %w", c.Prefix, name, err)
		}
		svg, _, err := icon.svg()
		if err != nil {
			return Result{}, fmt.Errorf("%s:%s: %w", c.Prefix, name, err)
		}
		exports = append(exports, Export{Name: symbol, ID: name, SHA256: artworkHash(svg)})
		literal := strconv.QuoteToASCII(svg)
		if source.Len()+len(literal)+1024 > MaxOutputBytes {
			return Result{}, fmt.Errorf("generated source exceeds %d bytes", MaxOutputBytes)
		}
		fmt.Fprintf(&source, "var icon%d iconCache\n\n// %s is the %s:%s icon.\n", index, symbol, c.Prefix, name)
		fmt.Fprintf(&source, "func %s() *ui.SVG { return icon%d.load(%s) }\n\n", symbol, index, literal)
	}
	exports, aliases, err := compatibleExports(exports, options.Previous)
	if err != nil {
		return Result{}, err
	}
	for _, e := range exports {
		if target, ok := aliases[e.Name]; ok {
			fmt.Fprintf(&source, "// %s is the %s:%s icon.\n// Deprecated: use %s.\nfunc %s() *ui.SVG { return %s() }\n\n", e.Name, c.Prefix, e.ID, target, e.Name, target)
		}
	}
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return Result{}, fmt.Errorf("format generated package: %w", err)
	}
	if len(formatted) > MaxOutputBytes {
		return Result{}, fmt.Errorf("formatted source exceeds %d bytes", MaxOutputBytes)
	}
	return Result{Source: formatted, Prefix: c.Prefix, Count: len(names), SHA256: sum, Exports: exports}, nil
}
